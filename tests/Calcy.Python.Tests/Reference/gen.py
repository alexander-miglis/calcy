# Regenerates CPythonReferenceTests.cs from the snippet files, running each snippet in CPython:
#   python -I gen.py cases.py,cases2.py,cases3.py ..\CPythonReferenceTests.cs
import io
import sys
import contextlib
import importlib.util

ALL = {}
for i, path in enumerate(sys.argv[1].split(",")):
    spec = importlib.util.spec_from_file_location("cases%d" % i, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    ALL.update(mod.CASES)
out_path = sys.argv[2]


def label(t):
    if t.__module__ in ("builtins", "__main__"):
        return t.__qualname__
    return t.__module__ + "." + t.__qualname__


def run(code):
    buf = io.StringIO()
    tail = ""
    with contextlib.redirect_stdout(buf):
        try:
            exec(compile(code, "<main>", "exec"), {"__name__": "__main__"})
        except SystemExit:
            pass
        except SyntaxError as e:
            tail = "!" + label(type(e)) + ": " + e.msg
        except BaseException as e:
            tail = "!" + label(type(e)) + ": " + str(e)
    return buf.getvalue() + tail


def cs(s):
    r = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            r.append("\\\\")
        elif ch == '"':
            r.append('\\"')
        elif ch == "\n":
            r.append("\\n")
        elif ch == "\r":
            r.append("\\r")
        elif ch == "\t":
            r.append("\\t")
        elif o < 32 or o > 126:
            if o > 0xFFFF:
                o -= 0x10000
                r.append("\\u%04X\\u%04X" % (0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF)))
            else:
                r.append("\\u%04X" % o)
        else:
            r.append(ch)
    r.append('"')
    return "".join(r)


lines = [
    "// <auto-generated>",
    "// Expected outputs were produced by CPython " + sys.version.split()[0] + " running the same snippets.",
    "// </auto-generated>",
    "namespace Calcy.Python.Tests;",
    "",
]
total = 0
for cat, snippets in ALL.items():
    lines.append(f"public class CPython{cat}Tests")
    lines.append("{")
    lines.append("    [Theory]")
    for code in snippets:
        lines.append(f"    [InlineData({cs(code)}, {cs(run(code))})]")
        total += 1
    lines.append("    public void MatchesCPython(string code, string expected) => Assert.Equal(expected, PyRun.Out(code));")
    lines.append("}")
    lines.append("")
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print("cases:", total)
